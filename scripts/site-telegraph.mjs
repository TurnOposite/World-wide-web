#!/usr/bin/env node
/**
 * The telegraph line's icon bank: site/assets/telegraph/* → site/data/telegraph.json.
 *
 * Ortis fills the folder with pictures (2026-11-10: « icons to select when
 * asked to join the telegraph line, coming from a folder I'll fill with pics
 * later »). A static host cannot list a folder, so the build does: this runs
 * at the start of every site build (scripts/site-build.mjs), which makes
 * « drop the pictures in, publish » the whole procedure. The copy of the list
 * kept in git is what a local `npm run site` serves between builds.
 *
 *   node scripts/site-telegraph.mjs          # write
 *   node scripts/site-telegraph.mjs --check  # exit 1 if the list is stale
 *
 * A file is in the bank when its name is one a message may carry
 * (server/lib/telegraph.js cleanIcon: letters, digits, - _ . only) and it is
 * a picture of at most MAX_BYTES. Anything else is left out and named.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const DIR = path.join(ROOT, 'site/assets/telegraph');
export const OUT = path.join(ROOT, 'site/data/telegraph.json');
export const EXTENSIONS = ['.png', '.jpg', '.jpeg', '.webp', '.gif', '.avif', '.svg'];
/** Past this a picture is too heavy to be one of dozens a join form loads at once. */
export const MAX_BYTES = 300 * 1024;
export const WARN_BYTES = 60 * 1024;
/** The same rule the tower applies to the icon a message names. */
export const NAME = /^[a-z0-9][a-z0-9._-]{0,63}$/i;

/** `03-blue_cat.png` → `blue cat`: what a screen reader says for the picture. */
export function labelOf(file) {
  return path.basename(file, path.extname(file)).replace(/^\d+[-_. ]+/, '').replace(/[-_.]+/g, ' ').trim() || 'icon';
}

/** The bank a folder holds: { icons: [{ file, label }], left: [{ file, why }], heavy: [file] }. */
export function iconBank(dir = DIR) {
  const icons = [];
  const left = [];
  const heavy = [];
  let names = [];
  try { names = fs.readdirSync(dir, { withFileTypes: true }).filter((e) => e.isFile()).map((e) => e.name); } catch { /* no folder: an empty bank */ }
  for (const file of names.sort((a, b) => a.localeCompare(b, 'en', { numeric: true }))) {
    const ext = path.extname(file).toLowerCase();
    if (!EXTENSIONS.includes(ext)) { if (ext !== '.md') left.push({ file, why: 'not a picture format the bank takes' }); continue; }
    if (!NAME.test(file) || file.includes('..')) { left.push({ file, why: 'its name has a space or a character other than letters, digits, - _ .' }); continue; }
    const size = fs.statSync(path.join(dir, file)).size;
    if (size > MAX_BYTES) { left.push({ file, why: `${Math.round(size / 1024)} KB — over ${MAX_BYTES / 1024} KB` }); continue; }
    if (size > WARN_BYTES) heavy.push(file);
    icons.push({ file, label: labelOf(file) });
  }
  return { icons, left, heavy };
}

export const manifest = (bank) => `${JSON.stringify({
  _readme: 'GENERATED by scripts/site-telegraph.mjs from site/assets/telegraph/ — the icons a listener can pick on the telegraph line. Change the folder, not this file.',
  icons: bank.icons,
}, null, 1)}\n`;

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const bank = iconBank();
  const want = manifest(bank);
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
  for (const l of bank.left) console.warn(`  ! left out of the telegraph's icons: ${l.file} (${l.why})`);
  if (bank.heavy.length) console.warn(`  ! heavy for an icon (over ${WARN_BYTES / 1024} KB): ${bank.heavy.join(', ')}`);
  if (process.argv.includes('--check')) {
    if (have !== want) { console.error('  ✗ site/data/telegraph.json is out of date with site/assets/telegraph/ — run: node scripts/site-telegraph.mjs'); process.exit(1); }
    console.log(`  ✓ the telegraph's icon bank is listed (${bank.icons.length} icons)`);
  } else {
    if (have !== want) fs.writeFileSync(OUT, want);
    console.log(`  ${have !== want ? '↻' : '✓'} site/data/telegraph.json — ${bank.icons.length} icons`);
  }
}
